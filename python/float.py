# Float variables
num1 = 5.0
num2 = 2.5

# Basic Arithmetic
result1 = num1 + num2
print("Addition:", result1)

result2 = num1 - num2
print("Subtraction:", result2)

result3 = 10 % 5
print("Multiplication:", result3)

result4 = 10 // 2.3
print("Division:", result4)
result6 = 9.2 // 7
print("Division:", result6)

# Rounding
result5 = round(3.14159265359, 9)  # Rounds to 2 decimal places
print("Rounded:", result5)